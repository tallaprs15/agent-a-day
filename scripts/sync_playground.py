"""Build playground/: one environment and one `adk web` UI for every agent.

For each day-*/ folder it writes a thin wrapper package playground/dayNNN_<pkg>/
that imports the real agent (ADK refuses symlinks that resolve outside its base
directory), and writes playground/pyproject.toml with the union of every
agent's dependencies.

    python3 scripts/sync_playground.py
    cd playground && uv sync && uv run adk web .
"""

from __future__ import annotations

import re
import shutil
import tomllib
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
PLAYGROUND = ROOT / "playground"


def agent_packages() -> list[Path]:
    return sorted(p.parent for p in ROOT.glob("day-*/*/agent.py") if (p.parent / "__init__.py").exists())


def requirement_name(req: str) -> str:
    return re.split(r"[<>=!~\[ ;]", req, maxsplit=1)[0].lower().replace("_", "-")


def main() -> None:
    PLAYGROUND.mkdir(exist_ok=True)
    packages = agent_packages()

    # Wrappers: playground/day001_arxiv_scout/agent.py -> imports day-001-*/arxiv_scout
    wanted = {}
    for pkg in packages:
        day = pkg.parent.name.split("-")[1]
        wanted[f"day{day}_{pkg.name}"] = pkg
    for entry in PLAYGROUND.iterdir():
        if entry.is_dir() and re.fullmatch(r"day\d{3}_\w+", entry.name) and entry.name not in wanted:
            shutil.rmtree(entry)
    for name, pkg in wanted.items():
        wrapper = PLAYGROUND / name
        wrapper.mkdir(exist_ok=True)
        (wrapper / "__init__.py").write_text("from . import agent  # noqa: F401\n")
        (wrapper / "agent.py").write_text(
            "# Generated by scripts/sync_playground.py\n"
            "import sys\n"
            "from pathlib import Path\n\n"
            f'sys.path.insert(0, str(Path(__file__).resolve().parents[2] / "{pkg.parent.name}"))\n\n'
            f"from {pkg.name}.agent import root_agent  # noqa: E402,F401\n"
        )

    # Union of dependencies; first spec seen for a package wins.
    deps: dict[str, str] = {}
    for pkg in packages:
        project = tomllib.loads((pkg.parent / "pyproject.toml").read_text())["project"]
        for req in project.get("dependencies", []):
            deps.setdefault(requirement_name(req), req)

    lines = [
        "# Generated by scripts/sync_playground.py. Do not edit by hand.",
        "[project]",
        'name = "agent-a-day-playground"',
        'version = "0.0.0"',
        'requires-python = ">=3.11"',
        "dependencies = [",
        *[f'    "{req}",' for _, req in sorted(deps.items())],
        "]",
        "",
        "[tool.uv]",
        "package = false",
        "",
    ]
    (PLAYGROUND / "pyproject.toml").write_text("\n".join(lines))
    print(f"playground: {len(wanted)} agents → {', '.join(wanted)}")


if __name__ == "__main__":
    main()
